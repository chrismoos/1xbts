function cave(lfsr: Uint8Array, reg: Uint8Array, offsets: Int32Array, rounds: number): void {
  const shuffle = new Uint8Array(16);
  const bitVal = (octet: number, bit: number) => ((octet & 0xff) << (7 - bit)) & 0x80;
  const lfsrCycle = () => {
    const carry = bitVal(lfsr[1], 6) ^ bitVal(lfsr[3], 2) ^ bitVal(lfsr[3], 1) ^ bitVal(lfsr[3], 0);
    for (let i = 3; i > 0; i--) {
      lfsr[i] = (lfsr[i] & 0xff) >> 1;
      if ((lfsr[i - 1] & 0x01) !== 0) lfsr[i] |= 0x80;
    }
    lfsr[0] = ((lfsr[0] & 0xff) >> 1) | carry;
  };
  const rotateRegisters = () => {
    const last = reg[15];
    for (let i = 15; i > 0; i--) {
      reg[i] = (reg[i] & 0xff) >> 1;
      if ((reg[i - 1] & 0x01) !== 0) reg[i] |= 0x80;
    }
    reg[0] = (reg[0] & 0xff) >> 1;
    if ((last & 0x01) !== 0) reg[0] |= 0x80;
  };
  for (let round = rounds - 1; round >= 0; round--) {
    const reg0 = reg[0];
    for (let r = 0; r < 16; r++) {
      let lowNibble = 0;
      let hiNibble = 0;
      let fail = 0;
      while (true) {
        offsets[0] = (offsets[0] + ((lfsr[0] & 0xff) ^ (reg[r] & 0xff))) & 0xff;
        lowNibble = CAVE_TABLE[offsets[0]] & 0x0f;
        if (lowNibble !== (reg[r] & 0x0f)) break;
        lfsrCycle();
        if (++fail === CAVE_RETRY_LIMIT) {
          lfsr[3] = (lfsr[3] + 1) & 0xff;
          break;
        }
      }
      fail = 0;
      while (true) {
        offsets[1] = (offsets[1] + ((lfsr[1] & 0xff) ^ (reg[r] & 0xff))) & 0xff;
        hiNibble = CAVE_TABLE[offsets[1]] & 0xf0;
        if (hiNibble !== (reg[r] & 0xf0)) break;
        lfsrCycle();
        if (++fail === CAVE_RETRY_LIMIT) {
          lfsr[3] = (lfsr[3] + 1) & 0xff;
          break;
        }
      }
      const mixed = (lowNibble | hiNibble) & 0xff;
      reg[r] = ((r === 15 ? reg0 : reg[r + 1]) ^ mixed) & 0xff;
      lfsrCycle();
    }
    rotateRegisters();
    for (let r = 0; r < 16; r++) shuffle[CAVE_TABLE[16 * round + r] & 0x0f] = reg[r];
    reg.set(shuffle);
  }
}

/**
 * The 6 A-key check digits over the A-key and ESN (S.S0053 §2.2.1). The
 * ESN bytes are big-endian. CAVE produces an 18-bit value in three bytes
 * (the top byte masked to 2 bits), converted to 6 decimal digits.
 */
export function akeyChecksum(akey: bigint, esn: number): string {
  const aKey = new Uint8Array(8);
  for (let i = 0; i < 8; i++) aKey[i] = Number((akey >> BigInt(8 * (7 - i))) & 0xffn);
  const e = Uint8Array.of((esn >>> 24) & 0xff, (esn >>> 16) & 0xff, (esn >>> 8) & 0xff, esn & 0xff);

  const lfsr = new Uint8Array(4);
  if ((aKey[0] | aKey[1] | aKey[2] | aKey[3]) !== 0) lfsr.set(aKey.subarray(0, 4));
  else lfsr.set(e);

  const reg = new Uint8Array(16);
  reg.set(aKey, 0);
  reg[8] = AAV;
  reg[9] = aKey[5];
  reg[10] = aKey[6];
  reg[11] = aKey[7];
  reg[12] = e[0];
  reg[13] = e[1];
  reg[14] = e[2];
  reg[15] = e[3];

  cave(lfsr, reg, Int32Array.of(128, 128), 8);

  const d = Uint8Array.of((reg[0] ^ reg[13]) & 0x03, (reg[1] ^ reg[14]) & 0xff, (reg[2] ^ reg[15]) & 0xff);
  const digits = new Array<number>(CHECK_DIGITS);
  for (let k = CHECK_DIGITS - 1; k >= 0; k--) {
    let rem = 0;
    for (let i = 0; i < 3; i++) {
      const cur = (rem << 8) | d[i];
      d[i] = Math.floor(cur / 10);
      rem = cur % 10;
    }
    digits[k] = rem;
  }
  return digits.join("");
}

