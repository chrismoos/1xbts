const AKEY_DIGITS = 20;
const CHECK_DIGITS = 6;
const AKEY_OCTETS = 8;
const BITS_PER_OCTET = 8n;

export function randomAKey(): string {
  const bytes = crypto.getRandomValues(new Uint8Array(AKEY_OCTETS));
  let value = 0n;
  for (const byte of bytes) value = (value << BITS_PER_OCTET) | BigInt(byte);
  return value.toString().padStart(AKEY_DIGITS, "0");
}

