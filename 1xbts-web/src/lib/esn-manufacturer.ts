/**
 * Extract the 8-bit manufacturer code from a 32-bit ESN.
 */
export function esnManufacturerCode(esn: number): number {
  return (esn >>> 24) & 0xff;
}

/**
 * Look up the manufacturer name for a 32-bit ESN.
 * Returns the manufacturer name, or null if the code is reserved/unknown.
 */
export function esnManufacturer(esn: number): string | null {
  const code = esnManufacturerCode(esn);
  return ESN_MANUFACTURERS[code] ?? null;
}
