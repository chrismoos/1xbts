float
wvq_a (float *z, int SIZE, int *path1, float (*cb1)[VECDIMa_NEW], float *wt,
       float *wmse)
   /* wt-ed VQ encoding */
{
    int k, n, ind = 0, N = VECDIMa_NEW;
    float mindist = INFINITY, dist, temp, mse;

    for (n = 0; n < SIZE; n++) {
	/* for each codevectors */
	dist = 0;

	for (k = 0; k < N; k++) {
	    temp = (z[k] - cb1[n][k]);
	    dist += temp * temp * wt[k];
	    if (dist > mindist)
		k = N + 10;
	}

	if (dist <= mindist) {
	    mindist = dist;
	    ind = n;
	}

    }				/* for-n */

    mse = mindist;

    path1[0] = ind;
    wmse[0] = mindist;

    return (mse);

}/********************* end wvq2 **********************/

